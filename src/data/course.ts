// Основная часть курса — модули 1–14. Модули 15–17 студент выбирает сам
// и осваивает самостоятельно, поэтому они помечены как направления по выбору.
export const CORE_END_ID = 14;
export const isElective = (id: number) => id > CORE_END_ID;
export const coreModules = modules.filter((m) => !isElective(m.id));
export const electiveModules = modules.filter((m) => isElective(m.id));
export const CORE_HOURS = coreModules.reduce((s, m) => s + m.hours, 0);
export const ELECTIVE_HOURS = electiveModules.reduce((s, m) => s + m.hours, 0);
export const TOTAL_HOURS = CORE_HOURS + ELECTIVE_HOURS;

export const formatHours = (hours: number) => new Intl.NumberFormat("ru-RU").format(hours);

